import { chromium } from 'playwright'
const browser = await chromium.launch()
const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 } })
const page = await ctx.newPage()
await page.goto('http://localhost:5173/', { waitUntil: 'networkidle', timeout: 15000 })
await page.waitForTimeout(3000)
await page.screenshot({ path: 'plans/hitl/phase-123/screenshots/welcome-before-fix.png', fullPage: true })
console.log('Saved welcome-before-fix.png')
await page.goto('http://localhost:5173/builder', { waitUntil: 'networkidle', timeout: 15000 })
await page.waitForTimeout(2500)
await page.screenshot({ path: 'plans/hitl/phase-123/screenshots/builder-before-fix.png', fullPage: true })
console.log('Saved builder-before-fix.png')
await page.goto('http://localhost:5173/agentics', { waitUntil: 'networkidle', timeout: 15000 })
await page.waitForTimeout(2000)
await page.screenshot({ path: 'plans/hitl/phase-123/screenshots/agentics-before-fix.png', fullPage: true })
console.log('Saved agentics-before-fix.png')
await browser.close()
