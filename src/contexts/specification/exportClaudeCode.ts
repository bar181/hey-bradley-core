/**
 * P96 / Agent A1 — exportClaudeCode emitter (markdown bundle).
 *
 * Hey Bradley is a SPEC FACTORY, not a code generator. This module turns a
 * `PhaseCard` (the SpecWorkbench atomic unit) into a single concatenated
 * markdown bundle the consumer (Claude Code, etc.) reads to implement in
 * their own repo. Per owner Q2 update: markdown bundle, NOT ZIP.
 *
 * Output shape:
 *   - `markdown` — single string with `# === FILE: <path> ===` markers
 *   - `files`    — logical file array (≥6) for testability + future
 *                  multi-file directory writes (Tier-2 File System Access API)
 *   - `slug`     — kebab-case slug (from projectSlug or phase.id)
 *   - `filename` — `{slug}-spec-bundle.md`
 *
 * Hard rules: pure module (no React / no store imports); no new deps;
 * TypeScript-strict (no `any`); explicit interfaces; ≤300 LOC including
 * JSDoc; output is HUMAN-READABLE markdown.
 *
 * See: ADR-122 (markdown bundle), ADR-101 (spec export quality),
 *      ADR-108 (AISP adoption), ADR-121 (SpecWorkbench).
 */
// P106 / A2 — Pure-module discipline per ADR-122 D1 + ADR-134: import spec
// types from the neutral types module, NOT from the React workbench.
import type { PhaseCard, SprintSummary } from '@/contexts/specification/types'
import { buildTDDScaffold } from '@/contexts/specification/exporters/tddScaffoldGenerator'

export interface ExportClaudeCodeBundle {
  /** Full markdown bundle as single string with file markers. */
  readonly markdown: string
  /** Logical files (testable + Tier-2 multi-file write target). */
  readonly files: ReadonlyArray<{ readonly path: string; readonly content: string }>
  /** kebab-case slug derived from projectSlug or phase.id. */
  readonly slug: string
  /** Suggested filename for browser download. */
  readonly filename: string
}

/** kebab-case slugifier; ASCII-only; collapses runs of separators. */
function slugify(s: string): string {
  return (
    s
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '') || 'spec-bundle'
  )
}

/** ISO date stamp (UTC, YYYY-MM-DD) for the preamble header. */
function isoDate(): string {
  return new Date().toISOString().slice(0, 10)
}

function buildClaudeMd(phase: PhaseCard): string {
  return [
    `# ${phase.name} — Spec Bundle`,
    '',
    `> Phase ${phase.phase} · Status: ${phase.status}`,
    `> Generated by Hey Bradley · ${isoDate()}`,
    '',
    '## Purpose',
    '',
    `This bundle is the complete spec for Phase ${phase.phase} (${phase.name}).`,
    'Hey Bradley is a spec factory — it produces DDD bounded contexts +',
    'ADRs + human spec + AISP spec. Code is downstream: read this bundle,',
    'then implement in your own repo.',
    '',
    '## Atoms (8 in production)',
    '',
    'PATCH · INTENT · SELECTION · CONTENT · ASSUMPTIONS · DECOMP · PROCESS · DDD · AGENT',
    '',
    '## Methodology (7-step)',
    '',
    '1. Research → 2. Decompose → 3. Architect (DDD + ADR) → 4. Spec (human + AISP)',
    '→ 5. Plan → 6. Build → 7. Reflect',
    '',
    '## Spec contents',
    '',
    '- process-map.md — visual phase/sprint/wave/agent breakdown',
    '- human-spec/north-star.md — vision (≤200 words)',
    '- human-spec/sadd.md — software architecture description (≤200 words)',
    '- human-spec/implementation-plan.md — what gets built (≤200 words)',
    '- aisp/phase-aisp.md — verbatim AISP Σ block (LLM-consumable)',
    '- adrs/ADR-{id}.md — one per cited ADR',
    '- agents/wave-{n}.md — one per sprint with agent scopes + DoD',
    '',
  ].join('\n')
}

function buildProcessMap(phase: PhaseCard): string {
  const rows = phase.sprints.length
    ? phase.sprints.map(
        (s) =>
          `| ${s.name} | ${s.status} | ${s.agentCount} | ${s.keyDeliverable} |`,
      )
    : ['| _(no sprints declared)_ | — | 0 | — |']
  return [
    `# Process Map — ${phase.name}`,
    '',
    `> Phase ${phase.phase} · ${phase.sprints.length} sprint(s)`,
    '',
    '| Sprint | Status | Agents | Key Deliverable |',
    '|---|---|---|---|',
    ...rows,
    '',
  ].join('\n')
}

function buildNorthStar(phase: PhaseCard): string {
  return ['# North Star', '', phase.humanSpec.northStar, ''].join('\n')
}

function buildSadd(phase: PhaseCard): string {
  return [
    '# Software Architecture Description (SADD)',
    '',
    phase.humanSpec.sadd,
    '',
  ].join('\n')
}

function buildImplementationPlan(phase: PhaseCard): string {
  return [
    '# Implementation Plan',
    '',
    phase.humanSpec.implementationPlan,
    '',
  ].join('\n')
}

function buildAispSpec(phase: PhaseCard): string {
  return [
    `# AISP Spec — ${phase.name}`,
    '',
    '```aisp',
    phase.aispSpec,
    '```',
    '',
  ].join('\n')
}

function buildAdrFile(adr: PhaseCard['adrRefs'][number]): string {
  const href =
    adr.href ?? `https://github.com/bar181/hey-bradley-core/blob/main/docs/adr/${adr.id}.md`
  return [`# ${adr.id} — ${adr.title}`, '', `See ${href}`, ''].join('\n')
}

function buildAgentWaveFile(sprint: SprintSummary, waveIndex: number): string {
  const lines: string[] = [`# Wave ${waveIndex} — ${sprint.name}`, '', '## Agent scopes', '']
  if (sprint.agentScopes && sprint.agentScopes.length > 0) {
    for (const agent of sprint.agentScopes) {
      lines.push(`### ${agent.role}`)
      lines.push(`- **Owns:** ${agent.ownedFiles.join(', ')}`)
      lines.push('')
    }
  } else {
    lines.push('TBD — populate from AGENT_ATOM at next plan iteration.')
    lines.push('')
  }
  lines.push('## Definition of Done', '')
  if (sprint.dod && sprint.dod.length > 0) {
    for (const item of sprint.dod) lines.push(`- [ ] ${item}`)
  } else {
    lines.push('TBD — populate from AGENT_ATOM at next plan iteration.')
  }
  lines.push('')
  return lines.join('\n')
}

/**
 * Build a Claude Code markdown bundle from a PhaseCard.
 *
 * Emits ≥6 logical files (CLAUDE.md, process-map.md, 3× human-spec/*.md,
 * aisp/phase-aisp.md, plus one adrs/ADR-*.md per adrRef and one
 * agents/wave-{n}.md per sprint). Concatenates into a single markdown
 * string with `# === FILE: <path> ===` separators between each file.
 *
 * @param phase        PhaseCard atomic unit (SpecWorkbench contract).
 * @param projectSlug  Optional project slug; falls back to phase.id then phase.name.
 */
export function buildClaudeCodeBundle(
  phase: PhaseCard,
  projectSlug?: string,
): ExportClaudeCodeBundle {
  const files: { path: string; content: string }[] = []

  files.push({ path: 'CLAUDE.md', content: buildClaudeMd(phase) })
  files.push({ path: 'process-map.md', content: buildProcessMap(phase) })
  files.push({ path: 'human-spec/north-star.md', content: buildNorthStar(phase) })
  files.push({ path: 'human-spec/sadd.md', content: buildSadd(phase) })
  files.push({
    path: 'human-spec/implementation-plan.md',
    content: buildImplementationPlan(phase),
  })
  files.push({ path: 'aisp/phase-aisp.md', content: buildAispSpec(phase) })

  for (const adr of phase.adrRefs) {
    files.push({ path: `adrs/${adr.id}.md`, content: buildAdrFile(adr) })
  }

  let waveIndex = 1
  for (const sprint of phase.sprints) {
    files.push({
      path: `agents/wave-${waveIndex}.md`,
      content: buildAgentWaveFile(sprint, waveIndex),
    })
    waveIndex += 1
  }

  // P97 / A2 — per-phase TDD test spec scaffold (sibling A1 module).
  const tddScaffold = buildTDDScaffold(phase)
  files.push({
    path: `phase-plans/${phase.id}-test-spec.md`,
    content: tddScaffold.markdown,
  })

  const markdown = files
    .map((f) => `# === FILE: ${f.path} ===\n\n${f.content}`)
    .join('\n')

  const slugSource = projectSlug ?? phase.id ?? phase.name
  const slug = slugify(slugSource)
  const filename = `${slug}-spec-bundle.md`

  return { markdown, files, slug, filename }
}
